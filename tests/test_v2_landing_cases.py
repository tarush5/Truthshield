"""
The landing page's example cases must be what the engines actually say.

frontend/src/components/landing/cases.json is generated by
scripts/landing_cases.py from offline runs of the synthetic demo samples. If
a rule change moves a score, this fails until the file is regenerated, so the
marketing page can never show a number the product would not produce.
"""

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _generator():
    spec = importlib.util.spec_from_file_location("landing_cases", ROOT / "scripts" / "landing_cases.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_landing_cases_match_the_engines():
    shown = json.loads((ROOT / "frontend" / "src" / "components" / "landing" / "cases.json").read_text(encoding="utf-8"))
    fresh = _generator().build()
    assert shown == fresh, "cases.json is stale: run `python scripts/landing_cases.py`"
